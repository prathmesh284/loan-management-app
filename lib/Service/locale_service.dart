class TranslationService extends Translations {
  static const String _localeStorageKey = 'app_locale';

  static const Locale fallbackLocale = Locale('en', 'US');
  static const Locale englishLocale = Locale('en', 'US');
  static const Locale marathiLocale = Locale('mr', 'IN');

  static Future<Locale> loadSavedLocale() async {
    final prefs = await SharedPreferences.getInstance();
    final storedLocale = prefs.getString(_localeStorageKey);
    return _localeFromCode(storedLocale);
  }

  static Locale _localeFromCode(String? code) {
    if (code == 'mr') {
      return marathiLocale;
    }
    return englishLocale;
  }

  static Future<void> changeLocale(Locale locale) async {
    final prefs = await SharedPreferences.getInstance();
    await prefs.setString(_localeStorageKey, locale.languageCode);
    Get.updateLocale(locale);
  }

  static Future<void> toggleLocale() async {
    final current = Get.locale ?? fallbackLocale;
    final nextLocale = current.languageCode == 'mr' ? englishLocale : marathiLocale;
    await changeLocale(nextLocale);
  }

  static bool isMarathi() => Get.locale?.languageCode == 'mr';
  static bool isEnglish() => Get.locale?.languageCode != 'mr';

